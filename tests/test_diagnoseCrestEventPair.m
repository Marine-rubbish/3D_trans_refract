function tests = test_diagnoseCrestEventPair
%TEST_DIAGNOSECRESTEVENTPAIR 验证点击诊断的双最近点和速度口径。
tests = functiontests(localfunctions);
end

function testEquivalentSpeedUsesPropagationPoint(testCase)
moorLat = 20.8;
moorLon = 115.7;
[crestLat, crestLon] = localPolylineToLatLon( ...
    [-10000,10000], [-10000,0], moorLat, moorLon);
crestTime = datetime(2020,5,7,12,0,0);
eventStart = crestTime-hours(2.1);
eventEnd = crestTime-hours(1.9);
config = diagnosticConfig(validDirection(90));

diagnostic = diagnoseCrestEventPair( ...
    crestLat, crestLon, crestTime, 1, ...
    moorLat, moorLon, eventStart, eventEnd, config);

verifyLessThan(testCase, ...
    diagnostic.geometricDistanceMeters, 5000);
verifyEqual(testCase, diagnostic.crossTrackMeters, 0, ...
    'AbsTol', 1e-6);
verifyEqual(testCase, ...
    diagnostic.alongDisplacementMeters, -10000, ...
    'AbsTol', 30);
verifyEqual(testCase, diagnostic.equivalentSpeedMidMps, ...
    diagnostic.alongDisplacementMeters/seconds( ...
    (eventStart+(eventEnd-eventStart)/2)-crestTime), ...
    'AbsTol', 1e-12);
verifyGreaterThan(testCase, ...
    distanceBetweenPoints( ...
    diagnostic.geometricPointLat, diagnostic.geometricPointLon, ...
    diagnostic.propagationPointLat, ...
    diagnostic.propagationPointLon, moorLat), ...
    1000);
verifyGreaterThan(testCase, ...
    diagnostic.equivalentSpeedMidMps, 1.3);
verifyLessThan(testCase, ...
    diagnostic.equivalentSpeedMidMps, 1.5);
end

function testInvalidDirectionStillReturnsGeometricPoint(testCase)
moorLat = 20.8;
moorLon = 115.7;
[crestLat, crestLon] = localPolylineToLatLon( ...
    [-3000,3000], [-1000,-1000], moorLat, moorLon);
crestTime = datetime(2020,5,7,12,0,0);
direction = validDirection(90);
direction.isValid = false;
direction.reason = "direction_flip_required_but_rejected";
config = diagnosticConfig(direction);

diagnostic = diagnoseCrestEventPair( ...
    crestLat, crestLon, crestTime, 1, ...
    moorLat, moorLon, crestTime-hours(1), ...
    crestTime-minutes(50), config);

verifyTrue(testCase, isfinite(diagnostic.geometricPointLat));
verifyTrue(testCase, isfinite(diagnostic.geometricDistanceMeters));
verifyTrue(testCase, isnan(diagnostic.propagationPointLat));
verifyTrue(testCase, isnan(diagnostic.equivalentSpeedMidMps));
verifyEqual(testCase, diagnostic.reason, ...
    "direction_flip_required_but_rejected");
end

function testRawSpeedAboveLimitRemainsVisible(testCase)
moorLat = 20.8;
moorLon = 115.7;
[crestLat, crestLon] = localPolylineToLatLon( ...
    [10000,20000], [0,-1000], moorLat, moorLon);
crestTime = datetime(2020,5,7,12,0,0);
config = diagnosticConfig(validDirection(90));

diagnostic = diagnoseCrestEventPair( ...
    crestLat, crestLon, crestTime, 1, ...
    moorLat, moorLon, crestTime-seconds(1050), ...
    crestTime-seconds(950), config);

verifyFalse(testCase, diagnostic.isPass);
verifyEqual(testCase, diagnostic.reason, "speed_above_5_mps");
verifyTrue(testCase, diagnostic.speedAboveLimit);
verifyEmpty(testCase, diagnostic.limitedSpeedIntervalsMps);
verifyGreaterThan(testCase, ...
    min(diagnostic.equivalentSpeedIntervalsMps(:,1)), 5);
verifyEqual(testCase, diagnostic.equivalentSpeedMidMps, 10, ...
    'AbsTol', 0.05);
end

function config = diagnosticConfig(direction)
config = struct( ...
    'searchToleranceSeconds', 60, ...
    'timeLimitSeconds', 86400*10, ...
    'radiusMeters', 100000, ...
    'directionResolution', direction);
end

function direction = validDirection(dirDeg)
direction = struct( ...
    'isValid', true, ...
    'initialDirDeg', dirDeg, ...
    'dirDeg', dirDeg, ...
    'flipRequired', false, ...
    'doFlip', true, ...
    'flipStats', struct(), ...
    'reason', "valid_without_flip");
end

function [lat, lon] = localPolylineToLatLon( ...
    x, y, moorLat, moorLon)
lat = moorLat + y/110540;
lon = moorLon + x/(111320*cosd(moorLat));
end

function distance = distanceBetweenPoints( ...
    latA, lonA, latB, lonB, referenceLat)
dx = (lonA-lonB)*111320*cosd(referenceLat);
dy = (latA-latB)*110540;
distance = hypot(dx, dy);
end
